"""Build the CRN-D concept (wide display in a reprinted beam) and its seated viewer set.

Concept only: the display is a placeholder; fit and strength UNKNOWN. Beam ends and context are the
Lab Rax creator's meshes (BY-NC-SA, personal use): viewer page not committed.

    python work/rgb-crown/build_crn_d.py [out_dir]
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_crn_a as A  # noqa: E402
import build_crn_c as Cc  # noqa: E402

F = A.F
PARTS = ("beam", "carrier", "panel", "screws")


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "build_d"
    view = out / "seated"
    view.mkdir(parents=True, exist_ok=True)
    d = json.loads((F.APP / "rack-references" / "component_1_23.json").read_text(encoding="utf-8"))
    loop = Cc.section_loop(d["vertices"], d["triangles"], Cc.PROFILE_X)
    (HERE / "crn_c_profile.scad").write_text(
        "// Generated by build_crn_c.py / build_crn_d.py: stock beam section at x = %d (y, z)\nPROFILE = %s;\n"
        % (Cc.PROFILE_X, json.dumps([list(p) for p in loop])), encoding="utf-8")
    beam = out / "beam_orig.stl"
    A.write_stl(beam, d["vertices"], d["triangles"])
    for part in PARTS:
        local = out / ("CRN-D_%s_local.stl" % part)
        subprocess.run([A.OPENSCAD, "-o", str(local), "-D", 'part="%s"' % part,
                        "-D", 'beam_stl="%s"' % beam.as_posix(), str(HERE / "crn_d.scad")], check=True)
        A.placed(local, F.I, A.BEAM_T, view / ("CRN-D_%s.stl" % part))
    n = 0
    for key, R, t in F.frame_parts():
        if key in {"panel_top", "side_rail", "handle"} and t[2] > 200 or (key == "post4" and t[2] > 200 and t[1] < 100):
            comp = json.loads((F.APP / "rack-references" / (F.SOURCES[key] + ".json")).read_text(encoding="utf-8"))
            src = out / "ctx.stl"
            A.write_stl(src, comp["vertices"], comp["triangles"])
            n += 1
            A.placed(src, R, t, view / ("ctx_%02d_%s.stl" % (n, key)))
            src.unlink()
    print("built", out)


if __name__ == "__main__":
    main()
