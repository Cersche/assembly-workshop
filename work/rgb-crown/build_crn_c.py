"""Build the CRN-C proposal (reprinted beam + bench-built panel cassette) and its seated viewer set.

Writes crn_c_profile.scad (the stock end-block section at x = 116, used as the solid middle profile),
renders every part with OpenSCAD and places rack copies plus frame context for the viewer.
Proposal only: panel numbers are placeholders; fit and strength UNKNOWN. Beam ends and context are
the Lab Rax creator's meshes (BY-NC-SA, personal use): viewer page not committed.

    python work/rgb-crown/build_crn_c.py [out_dir]
"""
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_crn_a as A  # noqa: E402

F = A.F
PROFILE_X = 116


def section_loop(verts, tris, x0):
    """Largest closed loop of the mesh section at x = x0, as [y, z] points."""
    adj = defaultdict(list)
    key = lambda p: (round(p[0], 4), round(p[1], 4))
    for t in tris:
        P = [verts[i] for i in t]
        pts = []
        for a in range(3):
            b = (a + 1) % 3
            sa, sb = P[a][0] - x0, P[b][0] - x0
            if (sa < 0) != (sb < 0):
                f = sa / (sa - sb)
                pts.append(key([P[a][k] + f * (P[b][k] - P[a][k]) for k in (1, 2)]))
        if len(pts) == 2:
            adj[pts[0]].append(pts[1])
            adj[pts[1]].append(pts[0])
    seen, loops = set(), []
    for s in list(adj):
        if s in seen:
            continue
        loop, cur = [s], s
        seen.add(s)
        while True:
            nxt = [n for n in adj[cur] if n not in seen]
            if not nxt:
                break
            cur = nxt[0]
            seen.add(cur)
            loop.append(cur)
        loops.append(loop)
    area = lambda L: abs(sum(L[i][0] * L[i - 1][1] - L[i - 1][0] * L[i][1] for i in range(len(L)))) / 2
    return max(loops, key=area)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "build_c"
    view = out / "seated"
    view.mkdir(parents=True, exist_ok=True)
    d = json.loads((F.APP / "rack-references" / "component_1_23.json").read_text(encoding="utf-8"))
    loop = section_loop(d["vertices"], d["triangles"], PROFILE_X)
    (HERE / "crn_c_profile.scad").write_text(
        "// Generated by build_crn_c.py: stock beam section at x = %d (y, z)\nPROFILE = %s;\n"
        % (PROFILE_X, json.dumps([list(p) for p in loop])), encoding="utf-8")
    beam = out / "beam_orig.stl"
    A.write_stl(beam, d["vertices"], d["triangles"])
    for part in ("beam", "tray", "bezel", "panel", "screws"):
        local = out / ("CRN-C_%s_local.stl" % part)
        subprocess.run([A.OPENSCAD, "-o", str(local), "-D", 'part="%s"' % part,
                        "-D", 'beam_stl="%s"' % beam.as_posix(), str(HERE / "crn_c.scad")], check=True)
        A.placed(local, F.I, A.BEAM_T, view / ("CRN-C_%s.stl" % part))
    keep = {"panel_top", "side_rail", "handle"}
    n = 0
    for key, R, t in F.frame_parts():
        if key in keep and t[2] > 200 or (key == "post4" and t[2] > 200 and t[1] < 100):
            comp = json.loads((F.APP / "rack-references" / (F.SOURCES[key] + ".json")).read_text(encoding="utf-8"))
            src = out / "ctx.stl"
            A.write_stl(src, comp["vertices"], comp["triangles"])
            n += 1
            A.placed(src, R, t, view / ("ctx_%02d_%s.stl" % (n, key)))
            src.unlink()
    print("built", out)


if __name__ == "__main__":
    main()
